"""Welch-test analysis for the PFT quantitative fluorescence pipeline.

The script uses independent image/ROI summaries generated by
``create_statistics_graphs.py`` in full mode. Individual cells are never treated
as independent observations. It performs:

* planned two-sided Welch tests for all eligible scalar ROI metrics;
* exploratory all-pairwise scalar comparisons in a separate output;
* pointwise Welch tests for axial and radial ROI profiles;
* multiplicity correction using Holm, Bonferroni, or Benjamini-Hochberg FDR;
* 95% confidence intervals and Hedges' g effect sizes;
* extraction of contiguous significant profile intervals;
* CSV, XLSX, and JSON outputs.

Example-mode outputs are rejected because one image per condition is not
sufficient for inferential statistics.
"""

