def result_to_row(
    *,
    dataset: str,
    metric: str,
    comparison: Comparison,
    result: WelchResult,
    family_id: str,
    correction: str,
    alpha: float,
) -> dict[str, object]:
    """Return result to row for the supplied inputs.

    Args:
        dataset (str): Dataset identifier that selects the supported acquisition and processing workflow, for example ``"2d_time"`` or ``"3d_data"``.
        metric (str): Text value specifying metric.
        comparison (Comparison): Value specifying comparison for the operation.
        result (WelchResult): Value specifying result for the operation.
        family_id (str): Text value specifying family id.
        correction (str): Text value specifying correction.
        alpha (float): Opacity coefficient used when blending image layers.

    Returns:
        dict[str, object]: Mapping containing the generated or resolved values.

    Example:
        >>> result = result_to_row(
        ...     dataset="2d_time",
        ...     metric="metric",
        ...     comparison=...,
        ...     result=...,
        ...     family_id="family_id",
        ...     correction="correction",
        ...     alpha=0.5,
        ... )
    """
    percentage_difference = (
        100.0 * result.difference_b_minus_a / abs(result.mean_a)
        if np.isfinite(result.mean_a) and abs(result.mean_a) > EPS
        else math.nan
    )
    return {
        "dataset": dataset,
        "metric": metric,
        "graph_target": graph_target(dataset, metric),
        "comparison": comparison.name,
        "comparison_role": comparison.role,
        "correction_family": family_id,
        "group_a": comparison.group_a_label,
        "group_a_conditions": ";".join(comparison.group_a_conditions),
        "group_b": comparison.group_b_label,
        "group_b_conditions": ";".join(comparison.group_b_conditions),
        "n_a_rois": result.n_a,
        "n_b_rois": result.n_b,
        "mean_a": result.mean_a,
        "sd_a": result.sd_a,
        "mean_b": result.mean_b,
        "sd_b": result.sd_b,
        "difference_b_minus_a": result.difference_b_minus_a,
        "percentage_difference_relative_to_a": percentage_difference,
        "standard_error": result.standard_error,
        "ci95_low": result.ci95_low,
        "ci95_high": result.ci95_high,
        "welch_t": result.t_statistic,
        "welch_df": result.degrees_of_freedom,
        "p_raw": result.p_raw,
        "p_adjusted": math.nan,
        "correction_method": correction,
        "alpha": alpha,
        "significant_after_correction": False,
        "hedges_g": result.hedges_g,
        "effect_size_magnitude": effect_size_magnitude(result.hedges_g),
        "status": result.status,
    }


def apply_family_correction(
    rows: list[dict[str, object]],
    correction: str,
    alpha: float,
) -> None:
    """Apply the configured operation to family correction.

    Args:
        rows (list[dict[str, object]]): Text value specifying rows.
        correction (str): Text value specifying correction.
        alpha (float): Opacity coefficient used when blending image layers.

    Example:
        >>> apply_family_correction(
        ...     rows="rows",
        ...     correction="correction",
        ...     alpha=0.5,
        ... )
    """
    families: dict[str, list[int]] = {}
    for index, row in enumerate(rows):
        if row.get("status") != "OK":
            continue
        families.setdefault(str(row["correction_family"]), []).append(index)
    for indices in families.values():
        adjusted = adjust_pvalues(
            [safe_float(rows[index].get("p_raw")) for index in indices], correction
        )
        for index, p_adjusted in zip(indices, adjusted):
            rows[index]["p_adjusted"] = p_adjusted
            rows[index]["significant_after_correction"] = bool(
                np.isfinite(p_adjusted) and p_adjusted < alpha
            )


def calculate_scalar_tests(
    dataset: str,
    rows: list[dict[str, str]],
    comparisons: Sequence[Comparison],
    correction: str,
    alpha: float,
    min_group_n: int,
    all_pairwise: bool,
) -> list[dict[str, object]]:
    """Calculate scalar tests from the supplied data.

    Args:
        dataset (str): Dataset identifier that selects the supported acquisition and processing workflow, for example ``"2d_time"`` or ``"3d_data"``.
        rows (list[dict[str, str]]): Text value specifying rows.
        comparisons (Sequence[Comparison]): Value specifying comparisons for the operation.
        correction (str): Text value specifying correction.
        alpha (float): Opacity coefficient used when blending image layers.
        min_group_n (int): Minimum permitted value of group n.
        all_pairwise (bool): Boolean flag controlling all pairwise.

    Returns:
        list[dict[str, object]]: Mapping containing the generated or resolved values.

    Example:
        >>> result = calculate_scalar_tests(
        ...     dataset="2d_time",
        ...     rows="rows",
        ...     comparisons=[],
        ...     correction="correction",
        ...     alpha=0.5,
        ...     min_group_n=1,
        ...     all_pairwise=True,
        ... )
    """
    metrics = numeric_metrics(rows)
    output: list[dict[str, object]] = []
    for metric in metrics:
        for comparison in comparisons:
            a = values_for_metric(rows, metric, comparison.group_a_conditions)
            b = values_for_metric(rows, metric, comparison.group_b_conditions)
            result = welch_test(a, b, min_group_n)
            family_id = scalar_family_id(dataset, metric, comparison, all_pairwise)
            output.append(
                result_to_row(
                    dataset=dataset,
                    metric=metric,
                    comparison=comparison,
                    result=result,
                    family_id=family_id,
                    correction=correction,
                    alpha=alpha,
                )
            )
    apply_family_correction(output, correction, alpha)
    return output


def read_roi_profiles(path: Path) -> dict[tuple[str, str, str], list[np.ndarray]]:
    """Read region of interest profiles from persistent storage.

    Args:
        path (Path): Filesystem path to the required input or output resource.

    Returns:
        dict[tuple[str, str, str], list[np.ndarray]]: Mapping containing the generated or resolved values.

    Example:
        >>> result = read_roi_profiles(path=Path("path/to/resource"))
    """
    store: dict[tuple[str, str, str], list[np.ndarray]] = {}
    with np.load(path) as archive:
        for key in archive.files:
            parts = key.split("|")
            if len(parts) < 4:
                continue
            condition, channel, _roi_identifier, profile_type = parts[0], parts[1], parts[2], parts[-1]
            if profile_type not in {"axial", "radial"}:
                continue
            profile = np.asarray(archive[key], dtype=np.float64)
            store.setdefault((condition, channel, profile_type), []).append(profile)
    return store


def collect_profiles(
    store: dict[tuple[str, str, str], list[np.ndarray]],
    conditions: Sequence[str],
    channel: str,
    profile_type: str,
) -> list[np.ndarray]:
    """Collect profiles from the available inputs.

    Args:
        store (dict[tuple[str, str, str], list[np.ndarray]]): Array containing store.
        conditions (Sequence[str]): Text value specifying conditions.
        channel (str): Channel index or channel identifier selected for processing.
        profile_type (str): Text value specifying profile type.

    Returns:
        list[np.ndarray]: Collection containing the generated or selected values.

    Example:
        >>> result = collect_profiles(
        ...     store=image_array,
        ...     conditions="conditions",
        ...     channel="channel",
        ...     profile_type="profile_type",
        ... )
    """
    profiles: list[np.ndarray] = []
    for condition in conditions:
        profiles.extend(store.get((condition, channel, profile_type), []))
    return profiles


def calculate_pointwise_profile_tests(
    dataset: str,
    store: dict[tuple[str, str, str], list[np.ndarray]],
    comparisons: Sequence[Comparison],
    profile_type: str,
    correction: str,
    alpha: float,
    min_group_n: int,
) -> list[dict[str, object]]:
    """Calculate pointwise profile tests from the supplied data.

    Args:
        dataset (str): Dataset identifier that selects the supported acquisition and processing workflow, for example ``"2d_time"`` or ``"3d_data"``.
        store (dict[tuple[str, str, str], list[np.ndarray]]): Array containing store.
        comparisons (Sequence[Comparison]): Value specifying comparisons for the operation.
        profile_type (str): Text value specifying profile type.
        correction (str): Text value specifying correction.
        alpha (float): Opacity coefficient used when blending image layers.
        min_group_n (int): Minimum permitted value of group n.

    Returns:
        list[dict[str, object]]: Mapping containing the generated or resolved values.

    Raises:
        ValueError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> result = calculate_pointwise_profile_tests(
        ...     dataset="2d_time",
        ...     store=image_array,
        ...     comparisons=[],
        ...     profile_type="profile_type",
        ...     correction="correction",
        ...     alpha=0.5,
        ...     min_group_n=1,
        ... )
    """
    output: list[dict[str, object]] = []
    for comparison in comparisons:
        for channel in CHANNELS[dataset]:
            profiles_a = collect_profiles(
                store, comparison.group_a_conditions, channel, profile_type
            )
            profiles_b = collect_profiles(
                store, comparison.group_b_conditions, channel, profile_type
            )
            if not profiles_a and not profiles_b:
                continue
            lengths = {profile.size for profile in (*profiles_a, *profiles_b)}
            if len(lengths) != 1:
                raise ValueError(
                    f"Profile lengths differ for {dataset}, {comparison.name}, "
                    f"{channel}, {profile_type}: {sorted(lengths)}"
                )
            profile_length = next(iter(lengths))
            matrix_a = (
                np.vstack(profiles_a)
                if profiles_a
                else np.empty((0, profile_length), dtype=np.float64)
            )
            matrix_b = (
                np.vstack(profiles_b)
                if profiles_b
                else np.empty((0, profile_length), dtype=np.float64)
            )
            family_id = (
                f"{dataset}::{comparison.name}::{channel}::{profile_type}::coordinates"
            )
            family_rows: list[dict[str, object]] = []
            for bin_index in range(profile_length):
                result = welch_test(
                    matrix_a[:, bin_index], matrix_b[:, bin_index], min_group_n
                )
                coordinate = (
                    bin_index / (profile_length - 1)
                    if profile_length > 1
                    else 0.0
                )
                family_rows.append(
                    {
                        "dataset": dataset,
                        "profile_type": profile_type,
                        "channel": channel,
                        "comparison": comparison.name,
                        "comparison_role": comparison.role,
                        "correction_family": family_id,
                        "group_a": comparison.group_a_label,
                        "group_b": comparison.group_b_label,
                        "coordinate_index": bin_index,
                        "normalized_coordinate": coordinate,
                        "n_a_rois": result.n_a,
                        "n_b_rois": result.n_b,
                        "mean_a": result.mean_a,
                        "sd_a": result.sd_a,
                        "mean_b": result.mean_b,
                        "sd_b": result.sd_b,
                        "difference_b_minus_a": result.difference_b_minus_a,
                        "standard_error": result.standard_error,
                        "ci95_low": result.ci95_low,
                        "ci95_high": result.ci95_high,
                        "welch_t": result.t_statistic,
                        "welch_df": result.degrees_of_freedom,
                        "p_raw": result.p_raw,
                        "p_adjusted": math.nan,
                        "correction_method": correction,
                        "alpha": alpha,
                        "significant_after_correction": False,
                        "hedges_g": result.hedges_g,
                        "effect_size_magnitude": effect_size_magnitude(result.hedges_g),
                        "status": result.status,
                    }
                )
            valid_indices = [
                index for index, row in enumerate(family_rows) if row["status"] == "OK"
            ]
            adjusted = adjust_pvalues(
                [safe_float(family_rows[index]["p_raw"]) for index in valid_indices],
                correction,
            )
            for index, p_adjusted in zip(valid_indices, adjusted):
                family_rows[index]["p_adjusted"] = p_adjusted
                family_rows[index]["significant_after_correction"] = bool(
                    np.isfinite(p_adjusted) and p_adjusted < alpha
                )
            output.extend(family_rows)
    return output


def significant_intervals(
    pointwise_rows: Sequence[dict[str, object]],
) -> list[dict[str, object]]:
    """Return significant intervals for the supplied inputs.

    Args:
        pointwise_rows (Sequence[dict[str, object]]): Text value specifying pointwise rows.

    Returns:
        list[dict[str, object]]: Mapping containing the generated or resolved values.

    Example:
        >>> result = significant_intervals(pointwise_rows="pointwise_rows")
    """
    grouped: dict[tuple[str, str, str, str], list[dict[str, object]]] = {}
    for row in pointwise_rows:
        if not bool(row.get("significant_after_correction", False)):
            continue
        key = (
            str(row.get("dataset", "")),
            str(row.get("profile_type", "")),
            str(row.get("channel", "")),
            str(row.get("comparison", "")),
        )
        grouped.setdefault(key, []).append(dict(row))

    intervals: list[dict[str, object]] = []
    for key, rows in grouped.items():
        rows.sort(key=lambda row: int(row["coordinate_index"]))
        current: list[dict[str, object]] = []
        previous_index: int | None = None
        previous_direction: str | None = None
        for row in rows:
            index = int(row["coordinate_index"])
            difference = safe_float(row.get("difference_b_minus_a"), 0.0)
            direction = "B > A" if difference > 0 else "A > B" if difference < 0 else "equal"
            if (
                current
                and previous_index is not None
                and (index != previous_index + 1 or direction != previous_direction)
            ):
                intervals.append(_interval_row(key, current, previous_direction or ""))
                current = []
            current.append(row)
            previous_index = index
            previous_direction = direction
        if current:
            intervals.append(_interval_row(key, current, previous_direction or ""))
    return intervals


def _interval_row(
    key: tuple[str, str, str, str],
    rows: Sequence[dict[str, object]],
    direction: str,
) -> dict[str, object]:
    """Return interval row for the supplied inputs.

    Args:
        key (tuple[str, str, str, str]): Key used to access or identify an entry in a mapping.
        rows (Sequence[dict[str, object]]): Text value specifying rows.
        direction (str): Text value specifying direction.

    Returns:
        dict[str, object]: Mapping containing the generated or resolved values.

    Example:
        >>> result = _interval_row(
        ...     key="key",
        ...     rows="rows",
        ...     direction="direction",
        ... )
    """
    dataset, profile_type, channel, comparison = key
    differences = np.asarray(
        [safe_float(row.get("difference_b_minus_a")) for row in rows], dtype=float
    )
    adjusted = np.asarray(
        [safe_float(row.get("p_adjusted")) for row in rows], dtype=float
    )
    first = rows[0]
    last = rows[-1]
    return {
        "dataset": dataset,
        "profile_type": profile_type,
        "channel": channel,
        "comparison": comparison,
        "group_a": first.get("group_a", ""),
        "group_b": first.get("group_b", ""),
        "start_bin": int(first["coordinate_index"]),
        "end_bin": int(last["coordinate_index"]),
        "start_coordinate": safe_float(first.get("normalized_coordinate")),
        "end_coordinate": safe_float(last.get("normalized_coordinate")),
        "n_consecutive_bins": len(rows),
        "direction": direction,
        "mean_difference_b_minus_a": float(np.nanmean(differences)),
        "minimum_adjusted_p": float(np.nanmin(adjusted)),
    }


def _excel_value(value: object) -> object:
    """Return excel value for the supplied inputs.

    Args:
        value (object): Value to validate, transform, store, or forward.

    Returns:
        object: Result produced by the operation.

    Example:
        >>> result = _excel_value(value=...)
    """
    if isinstance(value, (np.floating, np.integer, np.bool_)):
        value = value.item()
    if isinstance(value, float) and not np.isfinite(value):
        return None
    return value


def add_sheet_from_rows(workbook: Workbook, title: str, rows: Sequence[dict[str, object]]) -> None:
    """Add sheet from rows to the current data structure.

    Args:
        workbook (Workbook): Value specifying workbook for the operation.
        title (str): Title displayed on the generated figure or report section.
        rows (Sequence[dict[str, object]]): Text value specifying rows.

    Example:
        >>> add_sheet_from_rows(
        ...     workbook=...,
        ...     title="title",
        ...     rows="rows",
        ... )
    """
    sheet = workbook.create_sheet(title=title[:31])
    if not rows:
        sheet.append(["No results"])
        return
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    sheet.append(fields)
    for row in rows:
        sheet.append([_excel_value(row.get(field)) for field in fields])

    header_fill = PatternFill("solid", fgColor="1F4E78")
    for cell in sheet[1]:
        cell.fill = header_fill
        cell.font = Font(color="FFFFFF", bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    sheet.freeze_panes = "A2"
    sheet.auto_filter.ref = sheet.dimensions

    p_adjusted_col = fields.index("p_adjusted") + 1 if "p_adjusted" in fields else None
    if p_adjusted_col is not None and sheet.max_row >= 2:
        column_letter = get_column_letter(p_adjusted_col)
        sheet.conditional_formatting.add(
            f"{column_letter}2:{column_letter}{sheet.max_row}",
            CellIsRule(
                operator="lessThan",
                formula=["0.05"],
                fill=PatternFill("solid", fgColor="C6EFCE"),
            ),
        )

    for column_index, field in enumerate(fields, start=1):
        max_length = len(field)
        for cell in sheet[get_column_letter(column_index)]:
            value = "" if cell.value is None else str(cell.value)
            max_length = max(max_length, len(value))
        sheet.column_dimensions[get_column_letter(column_index)].width = min(max(max_length + 2, 11), 36)

    for row in sheet.iter_rows(min_row=2):
        for cell in row:
            if isinstance(cell.value, float):
                cell.number_format = "0.000000"


def write_workbook(
    path: Path,
    scalar_planned: Sequence[dict[str, object]],
    scalar_all_pairs: Sequence[dict[str, object]],
    axial_rows: Sequence[dict[str, object]],
    radial_rows: Sequence[dict[str, object]],
    intervals: Sequence[dict[str, object]],
    notes: Sequence[dict[str, object]],
) -> None:
    """Write workbook to persistent storage.

    Args:
        path (Path): Filesystem path to the required input or output resource.
        scalar_planned (Sequence[dict[str, object]]): Text value specifying scalar planned.
        scalar_all_pairs (Sequence[dict[str, object]]): Text value specifying scalar all pairs.
        axial_rows (Sequence[dict[str, object]]): Text value specifying axial rows.
        radial_rows (Sequence[dict[str, object]]): Text value specifying radial rows.
        intervals (Sequence[dict[str, object]]): Text value specifying intervals.
        notes (Sequence[dict[str, object]]): Text value specifying notes.

    Example:
        >>> write_workbook(
        ...     path=Path("path/to/resource"),
        ...     scalar_planned="scalar_planned",
        ...     scalar_all_pairs="scalar_all_pairs",
        ...     axial_rows="axial_rows",
        ...     radial_rows="radial_rows",
        ...     intervals="intervals",
        ...     notes="notes",
        ... )
    """
    workbook = Workbook()
    workbook.remove(workbook.active)
    add_sheet_from_rows(workbook, "scalar_planned", scalar_planned)
    add_sheet_from_rows(workbook, "scalar_all_pairs", scalar_all_pairs)
    add_sheet_from_rows(workbook, "axial_pointwise", axial_rows)
    add_sheet_from_rows(workbook, "radial_pointwise", radial_rows)
    add_sheet_from_rows(workbook, "significant_intervals", intervals)
    add_sheet_from_rows(workbook, "notes", notes)
    path.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(path)


def validate_full_mode_input(input_root: Path) -> dict[str, object]:
    """Validate full mode input against the required constraints.

    Args:
        input_root (Path): Directory used for input.

    Returns:
        dict[str, object]: Mapping containing the generated or resolved values.

    Raises:
        FileNotFoundError: If the supplied inputs or runtime state violate the function's requirements.
        RuntimeError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> result = validate_full_mode_input(input_root=Path("path/to/resource"))
    """
    summary_path = input_root / "graph_run_summary.json"
    if not summary_path.exists():
        raise FileNotFoundError(
            f"Missing graph_run_summary.json: {summary_path}. Run full graph generation first."
        )
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("run_mode") != "full":
        raise RuntimeError(
            f"Inferential testing requires full-mode ROI outputs, but {input_root} "
            f"reports run_mode={summary.get('run_mode')!r}. Remove --example and process all images first."
        )
    if str(input_root).lower().find("graphs_example") >= 0:
        raise RuntimeError("Example graph outputs cannot be used for Welch tests.")
    return summary


def prepare_output(path: Path, overwrite: bool) -> None:
    """Prepare output for downstream processing.

    Args:
        path (Path): Filesystem path to the required input or output resource.
        overwrite (bool): Whether an existing output may be replaced.

    Raises:
        FileExistsError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> prepare_output(path=Path("path/to/resource"), overwrite=True)
    """
    if path.exists() and any(path.iterdir()):
        if not overwrite:
            raise FileExistsError(f"Output directory is not empty: {path}. Use --overwrite.")
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def process_dataset(
    *,
    project_root: Path,
    dataset: str,
    source_mode: str,
    input_root: Path,
    output_root: Path,
    scalar_correction: str,
    profile_correction: str,
    alpha: float,
    min_group_n: int,
    overwrite: bool,
) -> dict[str, object]:
    """Process dataset using the configured workflow.

    Args:
        project_root (Path): Root directory of the PFT project containing the results, models, scripts, and source-code directories.
        dataset (str): Dataset identifier that selects the supported acquisition and processing workflow, for example ``"2d_time"`` or ``"3d_data"``.
        source_mode (str): Preprocessing source used to construct the input, such as the original image, a filtered image, or a U-Net-masked image.
        input_root (Path): Directory used for input.
        output_root (Path): Directory used for output.
        scalar_correction (str): Text value specifying scalar correction.
        profile_correction (str): Text value specifying profile correction.
        alpha (float): Opacity coefficient used when blending image layers.
        min_group_n (int): Minimum permitted value of group n.
        overwrite (bool): Whether an existing output may be replaced.

    Returns:
        dict[str, object]: Mapping containing the generated or resolved values.

    Raises:
        FileNotFoundError: If the supplied inputs or runtime state violate the function's requirements.
        ValueError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> result = process_dataset(
        ...     project_root=Path("path/to/resource"),
        ...     dataset="2d_time",
        ...     source_mode="original",
        ...     input_root=Path("path/to/resource"),
        ...     output_root=Path("path/to/resource"),
        ...     scalar_correction="scalar_correction",
        ...     profile_correction="profile_correction",
        ...     alpha=0.5,
        ...     min_group_n=1,
        ...     overwrite=True,
        ... )
    """
    summary = validate_full_mode_input(input_root)
    roi_summary_path = input_root / "roi_summary.csv"
    roi_profiles_path = input_root / "roi_profiles.npz"
    if not roi_summary_path.exists():
        raise FileNotFoundError(f"Missing ROI summary: {roi_summary_path}")
    if not roi_profiles_path.exists():
        raise FileNotFoundError(f"Missing ROI profiles: {roi_profiles_path}")

    prepare_output(output_root, overwrite)
    roi_rows = read_csv(roi_summary_path)
    if not roi_rows:
        raise ValueError(f"ROI summary is empty: {roi_summary_path}")
    conditions_present = sorted({str(row.get("condition", "")) for row in roi_rows})
    planned = planned_comparisons(dataset)
    pairwise = all_pairwise_comparisons(dataset, conditions_present)

    scalar_planned = calculate_scalar_tests(
        dataset,
        roi_rows,
        planned,
        scalar_correction,
        alpha,
        min_group_n,
        all_pairwise=False,
    )
    scalar_all_pairs = calculate_scalar_tests(
        dataset,
        roi_rows,
        pairwise,
        scalar_correction,
        alpha,
        min_group_n,
        all_pairwise=True,
    )

    profiles = read_roi_profiles(roi_profiles_path)
    axial_rows = calculate_pointwise_profile_tests(
        dataset,
        profiles,
        planned,
        "axial",
        profile_correction,
        alpha,
        min_group_n,
    )
    radial_rows = calculate_pointwise_profile_tests(
        dataset,
        profiles,
        planned,
        "radial",
        profile_correction,
        alpha,
        min_group_n,
    )
    intervals = significant_intervals([*axial_rows, *radial_rows])

    write_csv(output_root / "welch_scalar_planned.csv", scalar_planned)
    write_csv(output_root / "welch_scalar_all_pairwise.csv", scalar_all_pairs)
    write_csv(output_root / "welch_axial_pointwise.csv", axial_rows)
    write_csv(output_root / "welch_radial_pointwise.csv", radial_rows)
    write_csv(output_root / "welch_significant_profile_intervals.csv", intervals)

    notes = [
        {"item": "independent_observation", "value": "one image/ROI summary"},
        {"item": "test", "value": "two-sided Welch independent-samples t-test"},
        {"item": "difference_direction", "value": "mean(group B) - mean(group A)"},
        {"item": "confidence_interval", "value": "95% Welch confidence interval for the mean difference"},
        {"item": "effect_size", "value": "Hedges' g using pooled SD with small-sample correction"},
        {"item": "scalar_multiplicity_correction", "value": scalar_correction},
        {"item": "profile_multiplicity_correction", "value": profile_correction},
        {"item": "alpha", "value": alpha},
        {"item": "minimum_group_n", "value": min_group_n},
        {
            "item": "profile_inference",
            "value": "pointwise tests are exploratory and corrected across coordinates within each comparison/channel/profile family",
        },
        {
            "item": "example_mode",
            "value": "rejected because one image per condition is insufficient for inferential testing",
        },
        {
            "item": "3d_channel_comparisons",
            "value": "THY versus NHS is tested separately per channel; channel-versus-channel comparisons require paired analysis and are not tested here",
        },
    ]
    write_workbook(
        output_root / "welch_statistics.xlsx",
        scalar_planned,
        scalar_all_pairs,
        axial_rows,
        radial_rows,
        intervals,
        notes,
    )

    valid_scalar = [row for row in scalar_planned if row.get("status") == "OK"]
    significant_scalar = [
        row for row in valid_scalar if bool(row.get("significant_after_correction", False))
    ]
    valid_profile = [
        row for row in (*axial_rows, *radial_rows) if row.get("status") == "OK"
    ]
    significant_profile = [
        row
        for row in valid_profile
        if bool(row.get("significant_after_correction", False))
    ]
    analysis_summary = {
        "dataset": dataset,
        "source_mode": source_mode,
        "input_root": str(input_root),
        "output_root": str(output_root),
        "input_run_mode": summary.get("run_mode"),
        "n_roi_rows": len(roi_rows),
        "conditions_present": conditions_present,
        "scalar_correction_method": scalar_correction,
        "profile_correction_method": profile_correction,
        "alpha": alpha,
        "minimum_group_n": min_group_n,
        "n_planned_scalar_tests_valid": len(valid_scalar),
        "n_planned_scalar_tests_significant": len(significant_scalar),
        "n_pointwise_profile_tests_valid": len(valid_profile),
        "n_pointwise_profile_bins_significant": len(significant_profile),
        "n_significant_profile_intervals": len(intervals),
        "statistical_unit": "independent image/ROI",
        "warning": (
            "A statistically significant result does not establish biological importance. "
            "Interpret adjusted p-values together with confidence intervals, Hedges' g, "
            "effect direction, and the number of independent ROIs."
        ),
    }
    (output_root / "welch_statistics_summary.json").write_text(
        json.dumps(analysis_summary, indent=2), encoding="utf-8"
    )
    print(
        f"[WELCH] {dataset}: {len(valid_scalar)} valid planned scalar tests, "
        f"{len(significant_scalar)} significant after {scalar_correction}; "
        f"{len(intervals)} significant profile intervals"
    )
    print(f"Results: {output_root}")
    return analysis_summary


