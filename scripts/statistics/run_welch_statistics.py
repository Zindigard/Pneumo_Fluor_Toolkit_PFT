def find_project_root(explicit: Path | None = None) -> Path:
    """Find project root in the available data or project structure.

    Args:
        explicit (Path | None): Filesystem path used for explicit. ``None`` selects the function's default behavior.

    Returns:
        Path: Resolved or generated filesystem path.

    Raises:
        FileNotFoundError: If the supplied inputs or runtime state violate the function's requirements.
        RuntimeError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> result = find_project_root()
    """
    if explicit is not None:
        root = explicit.expanduser().resolve()
        if not (root / "scripts").is_dir():
            raise FileNotFoundError(f"Project root does not contain scripts/: {root}")
        return root
    search_start = SCRIPT_FILE.parent.resolve()
    for candidate in (search_start, *search_start.parents):
        if (candidate / "scripts").is_dir() and (candidate / "src" / "PFT").is_dir():
            return candidate
    raise RuntimeError("Cannot locate the PFT project root; provide --project-root.")


def read_csv(path: Path) -> list[dict[str, str]]:
    """Read CSV data from persistent storage.

    Args:
        path (Path): Filesystem path to the required input or output resource.

    Returns:
        list[dict[str, str]]: Mapping containing the generated or resolved values.

    Example:
        >>> result = read_csv(path=Path("path/to/resource"))
    """
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        return [dict(row) for row in csv.DictReader(handle)]


def write_csv(path: Path, rows: Sequence[dict[str, object]]) -> None:
    """Write CSV data to persistent storage.

    Args:
        path (Path): Filesystem path to the required input or output resource.
        rows (Sequence[dict[str, object]]): Text value specifying rows.

    Example:
        >>> write_csv(path=Path("path/to/resource"), rows="rows")
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def safe_float(value: object, default: float = math.nan) -> float:
    """Return safe float for the supplied inputs.

    Args:
        value (object): Value to validate, transform, store, or forward.
        default (float): Numerical value controlling default. Defaults to ``math.nan``.

    Returns:
        float: Computed numerical result.

    Example:
        >>> result = safe_float(value=...)
    """
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    return number if np.isfinite(number) else default


def numeric_metrics(rows: Sequence[dict[str, str]]) -> list[str]:
    """Return numeric metrics for the supplied inputs.

    Args:
        rows (Sequence[dict[str, str]]): Text value specifying rows.

    Returns:
        list[str]: Collection containing the generated or selected values.

    Example:
        >>> result = numeric_metrics(rows="rows")
    """
    metrics: list[str] = []
    for row in rows:
        for key, value in row.items():
            if key in NON_METRIC_COLUMNS or key in metrics:
                continue
            number = safe_float(value)
            if np.isfinite(number):
                metrics.append(key)
    return sorted(metrics)


def values_for_metric(
    rows: Sequence[dict[str, str]],
    metric: str,
    conditions: Sequence[str],
) -> np.ndarray:
    """Return values for metric for the supplied inputs.

    Args:
        rows (Sequence[dict[str, str]]): Text value specifying rows.
        metric (str): Text value specifying metric.
        conditions (Sequence[str]): Text value specifying conditions.

    Returns:
        np.ndarray: Array containing the processed result.

    Example:
        >>> result = values_for_metric(
        ...     rows="rows",
        ...     metric="metric",
        ...     conditions="conditions",
        ... )
    """
    selected = {
        condition for condition in conditions
    }
    values = np.asarray(
        [
            safe_float(row.get(metric))
            for row in rows
            if str(row.get("condition", "")) in selected
        ],
        dtype=np.float64,
    )
    return values[np.isfinite(values)]


def welch_test(a: np.ndarray, b: np.ndarray, min_group_n: int) -> WelchResult:
    """Return welch test for the supplied inputs.

    Args:
        a (np.ndarray): Array containing a.
        b (np.ndarray): Array containing b.
        min_group_n (int): Minimum permitted value of group n.

    Returns:
        WelchResult: Result produced by the operation.

    Example:
        >>> result = welch_test(
        ...     a=image_array,
        ...     b=image_array,
        ...     min_group_n=1,
        ... )
    """
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    a = a[np.isfinite(a)]
    b = b[np.isfinite(b)]
    n_a = int(a.size)
    n_b = int(b.size)
    mean_a = float(np.mean(a)) if n_a else math.nan
    mean_b = float(np.mean(b)) if n_b else math.nan
    sd_a = float(np.std(a, ddof=1)) if n_a > 1 else math.nan
    sd_b = float(np.std(b, ddof=1)) if n_b > 1 else math.nan
    difference = mean_b - mean_a if n_a and n_b else math.nan

    if n_a < min_group_n or n_b < min_group_n:
        return WelchResult(
            n_a,
            n_b,
            mean_a,
            sd_a,
            mean_b,
            sd_b,
            difference,
            math.nan,
            math.nan,
            math.nan,
            math.nan,
            math.nan,
            math.nan,
            math.nan,
            "INSUFFICIENT_N",
        )

    variance_a = sd_a**2
    variance_b = sd_b**2
    term_a = variance_a / n_a
    term_b = variance_b / n_b
    standard_error = math.sqrt(term_a + term_b)
    if standard_error <= EPS:
        p_raw = 1.0 if abs(difference) <= EPS else 0.0
        t_statistic = 0.0 if abs(difference) <= EPS else math.copysign(math.inf, difference)
        df = math.inf
        ci_low = difference
        ci_high = difference
    else:
        t_statistic = difference / standard_error
        denominator = (term_a**2) / (n_a - 1) + (term_b**2) / (n_b - 1)
        df = ((term_a + term_b) ** 2) / denominator if denominator > EPS else math.inf
        p_raw = float(2.0 * student_t.sf(abs(t_statistic), df))
        critical = float(student_t.ppf(0.975, df))
        ci_low = difference - critical * standard_error
        ci_high = difference + critical * standard_error

    pooled_denominator = n_a + n_b - 2
    if pooled_denominator > 0:
        pooled_variance = (
            (n_a - 1) * variance_a + (n_b - 1) * variance_b
        ) / pooled_denominator
        pooled_sd = math.sqrt(max(pooled_variance, 0.0))
    else:
        pooled_sd = math.nan
    if np.isfinite(pooled_sd) and pooled_sd > EPS:
        cohen_d = difference / pooled_sd
        correction = 1.0 - 3.0 / (4.0 * (n_a + n_b) - 9.0)
        hedges_g = correction * cohen_d
    else:
        hedges_g = 0.0 if abs(difference) <= EPS else math.nan

    return WelchResult(
        n_a,
        n_b,
        mean_a,
        sd_a,
        mean_b,
        sd_b,
        difference,
        standard_error,
        t_statistic,
        df,
        ci_low,
        ci_high,
        p_raw,
        hedges_g,
        "OK",
    )


def adjust_pvalues(values: Sequence[float], method: str) -> list[float]:
    """Return adjust pvalues for the supplied inputs.

    Args:
        values (Sequence[float]): Numerical value controlling values.
        method (str): Text value specifying method.

    Returns:
        list[float]: Collection containing the generated or selected values.

    Raises:
        ValueError: If the supplied inputs or runtime state violate the function's requirements.

    Example:
        >>> result = adjust_pvalues(values=0.5, method="method")
    """
    p = np.asarray(values, dtype=np.float64)
    adjusted = np.full(p.shape, np.nan, dtype=np.float64)
    finite_indices = np.flatnonzero(np.isfinite(p))
    if finite_indices.size == 0:
        return adjusted.tolist()
    finite_p = p[finite_indices]
    m = int(finite_p.size)

    if method == "bonferroni":
        corrected = np.minimum(1.0, finite_p * m)
    elif method == "holm":
        order = np.argsort(finite_p)
        ordered = finite_p[order]
        ordered_adjusted = np.empty_like(ordered)
        running = 0.0
        for rank, value in enumerate(ordered):
            candidate = (m - rank) * value
            running = max(running, candidate)
            ordered_adjusted[rank] = min(1.0, running)
        corrected = np.empty_like(ordered_adjusted)
        corrected[order] = ordered_adjusted
    elif method == "fdr_bh":
        order = np.argsort(finite_p)
        ordered = finite_p[order]
        ordered_adjusted = np.empty_like(ordered)
        running = 1.0
        for reverse_rank in range(m - 1, -1, -1):
            rank = reverse_rank + 1
            candidate = ordered[reverse_rank] * m / rank
            running = min(running, candidate)
            ordered_adjusted[reverse_rank] = min(1.0, running)
        corrected = np.empty_like(ordered_adjusted)
        corrected[order] = ordered_adjusted
    else:
        raise ValueError(f"Unsupported correction method: {method}")

    adjusted[finite_indices] = corrected
    return adjusted.tolist()


def effect_size_magnitude(value: float) -> str:
    """Return effect size magnitude for the supplied inputs.

    Args:
        value (float): Value to validate, transform, store, or forward.

    Returns:
        str: Generated or resolved text value.

    Example:
        >>> result = effect_size_magnitude(value=0.5)
    """
    if not np.isfinite(value):
        return "not_available"
    absolute = abs(value)
    if absolute < 0.2:
        return "negligible"
    if absolute < 0.5:
        return "small"
    if absolute < 0.8:
        return "medium"
    return "large"


def metric_base_for_3d(metric: str) -> str:
    """Return metric base for three-dimensional data for the supplied inputs.

    Args:
        metric (str): Text value specifying metric.

    Returns:
        str: Generated or resolved text value.

    Example:
        >>> result = metric_base_for_3d(metric="metric")
    """
    for channel in CHANNELS["3d_mip"]:
        prefix = f"{channel.lower()}_"
        if metric.startswith(prefix):
            return metric[len(prefix):]
    return metric


def graph_target(dataset: str, metric: str) -> str:
    """Return graph target for the supplied inputs.

    Args:
        dataset (str): Dataset identifier that selects the supported acquisition and processing workflow, for example ``"2d_time"`` or ``"3d_data"``.
        metric (str): Text value specifying metric.

    Returns:
        str: Generated or resolved text value.

    Example:
        >>> result = graph_target(dataset="2d_time", metric="metric")
    """
    lower = metric.lower()
    if metric == "n_cells":
        return "detected_cells"
    if "length" in lower and "axial_extent" not in lower:
        return "cell_length"
    if "homogeneity" in lower:
        return "homogeneity"
    if lower.startswith("dapi_axial_extent"):
        return "dapi_axial_signal_length"
    if "wga_dapi" in lower or "manders" in lower or "overlap" in lower or "pearson" in lower:
        return "wga_dapi_spatial_relationship"
    if "axial_" in lower or any(
        token in lower
        for token in (
            "pole1_intensity",
            "pole2_intensity",
            "midcell_intensity",
            "mean_pole_intensity",
            "midcell_to_pole_ratio",
            "pole_asymmetry",
        )
    ):
        return "axial_profile_summary"
    if "radial_" in lower or "boundary_to_centre" in lower or "centre_intensity" in lower or "boundary_intensity" in lower:
        return "radial_profile_summary"
    if dataset == "3d_mip":
        return "3d_channel_metric"
    return "scalar_metric"


