"""
Train reproducible two-dimensional Noise2Void models from original OME-Zarr data.

The module is the core implementation used by
``scripts/denoising/train_n2v_2d.py``.  Training inputs are discovered only at
``results/img/<dataset>/<sample>/image.ome.zarr``.  Normalized TIFF files,
preview PNG files, masks, and prior N2V outputs are never considered.

The workflow performs an image-level train/validation split before patch
extraction.  Consequently, patches from one biological image cannot occur in
both partitions.  No intensity normalization is performed.  Level-0 source
values are converted to ``float32`` only because the N2V model requires a
floating-point input.

Important parameters
--------------------
``patch_shape``
    Spatial patch size. Larger patches include more context but increase GPU
    memory use. Values must fit within every selected source frame.
``num_patches_per_image``
    Requested number of random patches generated by N2V. More patches improve
    sampling but increase preparation time and storage in memory.
``validation_fraction``
    Fraction of complete source images reserved for validation. It controls the
    independence and precision of the validation-loss estimate.
``epochs``
    Number of complete training epochs. Too few can underfit; too many can
    overfit, which is detected when validation loss increases.
``batch_size``
    Number of patches processed per optimization step. Larger batches require
    more GPU memory and may smooth gradient updates.
``unet_n_first`` and ``unet_n_depth``
    U-Net width and depth. Larger values increase representational capacity,
    training time, and memory consumption.
``n2v_perc_pix``
    Percentage of pixels manipulated for blind-spot training. Increasing it
    supplies more supervised targets per patch but can alter optimization.
``n2v_neighborhood_radius``
    Radius used to sample replacement values around manipulated pixels. It
    should exceed the approximate correlation scale of the noise without
    extending beyond relevant local image context.
"""

