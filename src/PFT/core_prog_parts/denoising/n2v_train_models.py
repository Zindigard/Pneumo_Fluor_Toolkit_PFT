@dataclass(frozen=True)
class SampleSplit:
    """Contain disjoint source-image partitions used for one model run."""

    train: tuple[Path, ...]
    validation: tuple[Path, ...]


@dataclass(frozen=True)
class TrainingResult:
    """Describe the completed training run and generated artifacts."""

    model_key: str
    model_name: str
    model_directory: Path
    artifact_directory: Path
    train_sample_count: int
    validation_sample_count: int
    train_patch_count: int
